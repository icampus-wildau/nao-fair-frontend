import { expect, test } from "@playwright/test"

test("dialog lines can be reordered, restored and configured", async ({ page }) => {
  await page.goto("/interaktionen")
  await page.getByRole("button", { name: /^Dialoge\b/ }).click()
  await page.getByRole("button", { name: "Neuer Dialog" }).click()
  await page.getByRole("button", { name: "Zeile hinzufügen" }).click()
  await page.getByRole("textbox", { name: "Zeile 1" }).fill("Erste Zeile")
  await page.getByRole("button", { name: "Zeile unter 1 einfügen" }).click()
  await page.getByRole("textbox", { name: "Zeile 2" }).fill("Zweite Zeile")
  const side = page.getByRole("button", { name: "Zeile 2, NAO. Zu Mensch wechseln." })
  await expect(side).toHaveAttribute("title", "NAO. Zu Mensch wechseln.")
  await side.click()
  await expect(page.getByText("Nur zur Planung")).toBeVisible()
  await expect(page.getByRole("combobox", { name: "Wiedergabe für Zeile 2" })).toHaveCount(0)
  await page.getByRole("button", { name: "Zeile 2, Mensch. Zu NAO wechseln." }).click()
  await page.getByRole("combobox", { name: "Wiedergabe für Zeile 2" }).selectOption("motion")
  await expect(page.getByRole("combobox", { name: "Bewegung für Zeile 2" })).toBeVisible()
  await page.getByLabel("Zeile 2 verschieben").click()
  await page.getByRole("button", { name: "Nach oben" }).click()
  await expect(page.getByRole("textbox", { name: "Zeile 1" })).toHaveValue("Zweite Zeile")
  await page.getByRole("button", { name: "Zeile 1 löschen" }).click()
  await page.getByRole("button", { name: "Rückgängig" }).click()
  await expect(page.getByRole("textbox", { name: "Zeile 1" })).toHaveValue("Zweite Zeile")
  await expect(page.getByRole("combobox", { name: "Bewegung für Zeile 1" })).toBeVisible()
  await page.locator(".dialog-line").first().locator(".dialog-drag").dragTo(page.locator(".dialog-line").nth(1), { targetPosition: { x: 10, y: 35 } })
  await expect(page.getByRole("textbox", { name: "Zeile 2" })).toHaveValue("Zweite Zeile")
  await expect(page.getByRole("textbox", { name: "Dialogname" })).toBeVisible()
})

test("a connected robot can speak an unsaved NAO line", async ({ page, request }) => {
  await request.post("/api/robot/disconnect")
  await page.goto("/interaktionen")
  await page.getByRole("button", { name: /^Dialoge\b/ }).click()
  await page.getByRole("button", { name: "Neuer Dialog" }).click()
  await page.getByRole("button", { name: "Zeile hinzufügen" }).click()
  const testButton = page.getByRole("button", { name: "Text von Zeile 1 testen" })
  await page.getByRole("textbox", { name: "Zeile 1" }).fill("Noch nicht übernommener Text")
  await expect(testButton).toBeDisabled()
  await request.post("/api/test/driver", { data: { events: [{ type: "picture", connection: { state: "connected", address: "192.0.2.10" }, conversation_state: "idle" }] } })
  await expect(testButton).toBeEnabled()
  const spoken = page.waitForRequest((req) => req.url().includes("/api/speech/speak") && req.method() === "POST")
  await testButton.click()
  expect((await spoken).postDataJSON()).toEqual({ text: "Noch nicht übernommener Text" })
  await page.getByRole("button", { name: "Zeile 1, NAO. Zu Mensch wechseln." }).click()
  await expect(testButton).toHaveCount(0)
})
