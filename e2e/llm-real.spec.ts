import { expect, test } from '@playwright/test'

test('Markdown draft reset and text-only apply use the real offline server', async ({ page }) => {
  await page.goto('/llm')
  await page.locator('.content-row:has(input:checked) .content-choice').dblclick()
  const editor = page.locator('.cm-content')
  await expect(editor).toBeVisible()
  const appliedBefore = await (await page.request.get('/api/config/applied')).json()
  const promptId = appliedBefore.applied.system_prompt_id
  const original = await (await page.request.get(`/api/content/${promptId}`)).json()
  const snapshotBefore = await (await page.request.get('/api/config/applied-content')).json()
  expect(original.markdown).toBe(snapshotBefore.items[promptId])
  const suffix = ' LLM-Prüfung'
  await editor.click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.type(suffix)
  await expect(page.getByRole('button', { name: 'Übernehmen' })).toBeEnabled()
  await page.getByRole('button', { name: 'Zurücksetzen' }).click()
  await expect(editor).not.toContainText(suffix)
  expect((await (await page.request.get(`/api/content/${promptId}`)).json()).markdown).toBe(original.markdown)
  await editor.click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.type(suffix)
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await expect(page.getByText('Übernommen.', { exact: true })).toBeVisible()
  await page.reload()
  await page.locator('.content-row:has(input:checked) .content-choice').dblclick()
  await expect(page.locator('.cm-content')).toBeVisible()
  const saved = await (await page.request.get(`/api/content/${promptId}`)).json()
  const snapshot = await (await page.request.get('/api/config/applied-content')).json()
  expect(saved.markdown).toContain(suffix)
  expect(snapshot.items[promptId]).toBe(saved.markdown)
  await expect(page.getByRole('region', { name: 'Offene Änderungen' })).toHaveCount(0)

  // A previous save may have succeeded even if the following Apply failed.
  const state = await (await page.request.get('/api/config/applied')).json()
  const id = state.applied.system_prompt_id
  const item = await (await page.request.get(`/api/content/${id}`)).json()
  await page.request.put(`/api/content/${id}`, { data: { name: item.name, markdown: `${item.markdown} offen` } })
  await page.reload()
  await expect(page.getByText('Gespeicherte Texte sind noch nicht übernommen.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Übernehmen' })).toBeEnabled()
  await page.getByRole('button', { name: 'Zurücksetzen' }).click()
  expect((await (await page.request.get(`/api/content/${id}`)).json()).markdown).toBe(saved.markdown)
  await expect(page.getByRole('region', { name: 'Offene Änderungen' })).toHaveCount(0)
})

test('all LLM sections, vocabulary and component presets work without a robot', async ({ page }) => {
  await page.goto('/llm')
  for (const label of ['System-Prompt', 'Hintergrundwissen', 'Örtlicher Kontext', 'Persönlichkeit', 'TTS-Ersetzungen', 'STT-Vokabular']) {
    await page.getByRole('navigation', { name: 'Inhalte' }).getByRole('button', { name: label }).click()
    await expect(page.locator('.studio article').first().getByRole('heading', { name: label, exact: true })).toBeVisible()
  }
  await page.getByLabel('Neuer Begriff').fill('Testbegriff')
  await page.getByRole('button', { name: 'Hinzufügen', exact: true }).click()
  await page.getByRole('navigation', { name: 'Inhalte' }).getByRole('button', { name: 'TTS-Ersetzungen' }).click()
  await page.getByRole('button', { name: 'Zeile hinzufügen' }).click()
  const sources = page.getByLabel('Quelle', { exact: true })
  const replacements = page.getByLabel('Ersetzung', { exact: true })
  await sources.first().fill('Testquelle')
  await sources.first().press('Tab')
  await page.locator('.replacement-row').filter({ has: page.locator('input[aria-label="Quelle"][value="Testquelle"]') }).getByRole('textbox', { name: 'Ersetzung', exact: true }).fill('Testlaut')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await expect(page.getByText('Übernommen.', { exact: true })).toBeVisible()
  const state = await (await page.request.get('/api/config/applied')).json()
  expect(state.applied.stt_vocabulary).toContainEqual({ term: 'Testbegriff', enabled: true })
  expect(state.applied.tts_replacements).toContainEqual({ source: 'Testquelle', replacement: 'Testlaut', enabled: true })
  await page.getByRole('navigation', { name: 'Inhalte' }).getByRole('button', { name: 'Presets' }).click()
  await page.getByRole('button', { name: 'Neues Preset', exact: true }).click()
  await page.getByRole('combobox', { name: 'Art', exact: true }).selectOption('tts_replacements')
  await page.getByLabel('Neues Preset', { exact: true }).fill('TTS Testpreset')
  await page.getByRole('button', { name: 'Preset speichern', exact: true }).last().click()
  await expect(page.locator('.preset-row').filter({ hasText: 'TTS Testpreset' })).toBeVisible()
  await page.getByRole('button', { name: 'Menü für Preset TTS Testpreset', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Duplizieren', exact: true }).click()
  await expect(page.locator('.preset-row').filter({ hasText: 'TTS Testpreset Kopie' })).toBeVisible()
  const presets = await (await page.request.get('/api/presets')).json()
  expect(presets.find((item: { name: string }) => item.name === 'TTS Testpreset').payload.replacements).toContainEqual({ source: 'Testquelle', replacement: 'Testlaut', enabled: true })
  await page.getByRole('combobox', { name: 'Preset-Art filtern' }).selectOption('llm')
  await page.getByRole('button', { name: 'Standard laden', exact: true }).click()
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  }
})
