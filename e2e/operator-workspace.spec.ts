test('changing TTS priority keeps the alphabetic row and focused rule stable', async ({ page }) => {
  await page.goto('/llm?abschnitt=tts')
  const rows = page.locator('.replacement-row')
  await expect(rows.first()).toBeVisible()
  const existing = await rows.count()
  for (const [source, replacement] of [['Alpha Priorität', 'A'], ['Zulu Priorität', 'Z']]) {
    await page.getByRole('button', { name: 'Zeile hinzufügen', exact: true }).click()
    const empty = rows.filter({ has: page.locator('input[aria-label="Quelle"][value=""]') }).first()
    await empty.getByRole('textbox', { name: 'Quelle', exact: true }).fill(source!)
    await empty.getByRole('textbox', { name: 'Quelle', exact: true }).press('Tab')
    const row = rows.filter({ has: page.locator(`input[aria-label="Quelle"][value="${source}"]`) })
    await row.getByRole('textbox', { name: 'Ersetzung', exact: true }).fill(replacement!)
    await row.getByRole('textbox', { name: 'Ersetzung', exact: true }).press('Tab')
  }
  const zulu = rows.filter({ has: page.locator('input[aria-label="Quelle"][value="Zulu Priorität"]') })
  const top = (await zulu.boundingBox())!.y
  for (const priority of [existing + 1, existing]) {
    await zulu.getByRole('button', { name: 'Regel nach oben', exact: true }).click()
    await expect(zulu.locator('.num')).toHaveText(String(priority))
    if (priority > 1) await expect(zulu.getByRole('button', { name: 'Regel nach oben', exact: true })).toBeFocused()
    expect((await zulu.boundingBox())!.y).toBe(top)
  }
  await page.getByRole('button', { name: 'Zurücksetzen', exact: true }).click()
})
