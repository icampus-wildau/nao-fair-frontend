test('full text search, alphabetical sorting, applied markers and view state survive section switches', async ({ page, request }) => {
  const items: any[] = []
  for (const [name, markdown] of [['Zulu Suche', 'Einzigartige Textnadel'], ['Alpha Suche', 'Anderer Text']]) items.push(await (await request.post('/api/content', { data: { kind: 'knowledge', name, markdown } })).json())
  await page.goto('/llm?abschnitt=knowledge')
  const choices = page.locator('.content-choice')
  const names = await choices.allTextContents()
  expect(names.findIndex(name => name.includes('Alpha Suche'))).toBeLessThan(names.findIndex(name => name.includes('Zulu Suche')))
  await page.getByRole('searchbox', { name: 'Bausteine suchen' }).fill('Textnadel')
  await expect(choices).toHaveCount(1)
  await expect(choices).toContainText('Zulu Suche')
  await expect(page.locator('.search-excerpt')).toContainText('Textnadel')
  await page.getByRole('navigation', { name: 'Inhalte' }).getByRole('button', { name: 'Modell / Generierung' }).click()
  await page.getByRole('navigation', { name: 'Inhalte' }).getByRole('button', { name: 'Hintergrundwissen' }).click()
  await expect(page.getByRole('searchbox', { name: 'Bausteine suchen' })).toHaveValue('Textnadel')
  await page.getByRole('navigation', { name: 'Inhalte' }).getByRole('button', { name: 'System-Prompt' }).click()
  await expect(page.locator('.applied-marker').filter({ hasText: 'Übernommen' })).toHaveCount(1)
  for (const item of items) await request.delete(`/api/content/${item.id}`)
})

test('draft recovery is explicit and confirmed discard never resurrects a draft', async ({ page, request }) => {
  await page.goto('/roboter')
  await page.getByText('Gesprächszeiten', { exact: true }).click()
  const state = (await (await request.get('/api/config/applied')).json()).applied
  const timing = page.getByRole('spinbutton', { name: 'Zuhör-Timeout', exact: true })
  const value = state.listening_timeout_secs === 17.5 ? '18.5' : '17.5'
  await timing.fill(value)
  await expect.poll(async () => page.evaluate(() => localStorage.getItem('nao-fair.draft-backup'))).toContain(value)
  page.once('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(page.getByRole('region', { name: 'Entwurf wiederherstellen' })).toBeVisible()
  await expect(timing).toHaveValue(String(state.listening_timeout_secs))
  await page.getByRole('button', { name: 'Wiederherstellen', exact: true }).click()
  await expect(timing).toHaveValue(value)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('region', { name: 'Entwurf wiederherstellen' })).toHaveCount(0)
})

