import { expect, test } from '@playwright/test'

for (const width of [320, 390, 768, 1024]) {
  test(`mobile scenario and navigation remain usable at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 800 })
    await page.goto('/llm?abschnitt=scenario')
    const list = page.locator('.scenario-row').first()
    await expect(list).toBeVisible()
    await expect(page.getByRole('button', { name: 'Aktuelle Konfiguration als neues Szenario speichern' })).toBeVisible()
    await expect(list.getByRole('button', { name: 'Szenario laden' })).toBeVisible()
    await page.getByRole('button', { name: 'Aktuelle Konfiguration ansehen' }).click()
    await expect(page.getByLabel('Name', { exact: true })).toBeVisible()
    await page.getByLabel('Name', { exact: true }).fill('Mobiler Entwurf')
    await page.getByRole('button', { name: 'Zurück zur Szenarioliste' }).click()
    await expect(list).toBeVisible()
    await page.getByRole('button', { name: 'Aktuelle Konfiguration ansehen' }).click()
    await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Mobiler Entwurf')
    await page.getByRole('button', { name: 'Zurück zur Szenarioliste' }).click()
    await list.locator('.scenario-choice').click()
    await expect(page.locator('.scenario-detail')).toBeVisible()
    await page.getByRole('button', { name: 'Zurück zur Szenarioliste' }).click()
    const nav = page.getByRole('navigation', { name: 'Inhalte' })
    await nav.getByRole('button', { name: 'Szenario', exact: true }).first().click()
    await nav.getByRole('button', { name: /Modell \/ Generierung/ }).click()
    await expect(page.getByLabel('Modell', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  })
}

test('phone drawer exposes connection and closes accessibly', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('/')
  await expect(page.locator('#robot-address')).toBeHidden()
  await page.getByRole('button', { name: 'Menü öffnen' }).click()
  const drawer = page.getByRole('dialog', { name: 'Menü' })
  await expect(drawer).toBeVisible()
  await expect(drawer.getByLabel('IP-Adresse')).toBeVisible()
  await expect(drawer.getByRole('button', { name: 'Verbinden' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('button', { name: 'Menü öffnen' })).toBeFocused()
  await page.getByRole('button', { name: 'Menü öffnen' }).click()
  await drawer.getByRole('link', { name: 'System' }).click()
  await expect(drawer).toBeHidden()
  await expect(page).toHaveURL(/system/)
})

test('phone interactions switch between trigger list and action', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/llm?abschnitt=interactions')
  const gesture = page.locator('.interaction-list .gesture[role="button"]').first()
  await gesture.click()
  await expect(page.getByRole('heading', { name: 'Aktion zuordnen' })).toBeVisible()
  await expect(page.locator('.interaction-list')).toBeHidden()
  await page.getByRole('button', { name: 'Zurück zu Auslösern' }).click()
  await expect(gesture).toBeVisible()
})
